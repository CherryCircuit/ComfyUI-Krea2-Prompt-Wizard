"""Build the universal Prompt Studio starter library.

The original studio presets were written as Krea 2 "scene bibles" for one
recurring fantasy production. This script adds a model-agnostic vocabulary
for ordinary prompt building: short, concrete, visual descriptions that
read the same to Flux, SDXL, Krea 2, Wan, LTX or a video model.

Every preset carries a ``collection`` ("Medieval", "Sci-Fi", "School"…)
so the chooser and the randomizer pool tree can group options by type.

Run from the repo root:

    python scripts/build_studio_universal.py

Generated JSON is checked in; the script is the maintainable source for
this block of the library.
"""
from __future__ import annotations

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STUDIO_DIR = os.path.join(ROOT, "presets", "studio")


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


_SLOT_BY_COLLECTION = {
    ("camera", "Framing"): "framing",
    ("camera", "Angle"): "angle",
    ("camera", "Lens"): "lens",
    ("camera", "Movement"): "movement",
    ("lighting", "Natural"): "lighting_time",
    ("lighting", "Practical"): "lighting_source",
    ("lighting", "Cinematic"): "lighting_quality",
    ("lighting", "Studio"): "lighting_quality",
    ("lighting", "Dramatic"): "lighting_quality",
    ("lighting", "Direction"): "lighting_direction",
    ("style", "Color Grade"): "color_grade",
}

_SLOT_BY_NAME = {
    ("lighting", "Neon Practicals"): "lighting_source",
}


def preset(
    prefix: str,
    name: str,
    category: str,
    collection: str,
    prompt: str,
    *,
    negative: str = "",
    description: str = "",
    tags: tuple[str, ...] = (),
    group: str | None = None,
) -> dict:
    slot = group if group is not None else _SLOT_BY_COLLECTION.get(
        (category, collection), category
    )
    # The camera entries predate the framing/angle/lens/movement split and
    # still pass group="camera"; let the collection decide their real slot.
    if category == "camera" and slot == "camera":
        slot = _SLOT_BY_COLLECTION.get((category, collection), "framing")
    slot = _SLOT_BY_NAME.get((category, name), slot)
    return {
        "id": f"{prefix}_{slug(name)}",
        "name": name,
        "category": category,
        "collection": collection,
        "prompt": prompt,
        "negative": negative,
        "description": description,
        "tags": list(tags or (collection.lower(),)),
        "notes": "",
        "enabled": True,
        "reference_images": [],
        "exclusive_group": slot,
    }


