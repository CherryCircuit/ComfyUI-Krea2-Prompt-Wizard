def main() -> None:
    for filename, mapping in BY_FILE.items():
        path = os.path.join(STUDIO_DIR, filename)
        with open(path, "r", encoding="utf-8") as handle:
            payload = json.load(handle)
        changed = 0
        for entry in payload.get("presets", []):
            collection = mapping.get(entry["id"], mapping.get("*"))
            if collection and entry.get("collection") != collection:
                entry["collection"] = collection
                changed += 1
        if changed:
            with open(path, "w", encoding="utf-8") as handle:
                json.dump(payload, handle, indent=2, ensure_ascii=False)
                handle.write("\n")
        print(f"{filename}: {changed} updated")


if __name__ == "__main__":
    main()
